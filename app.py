# 辅助函数: 生成 RDKit 2D 图像的 Base64 编码 (不变)
def generate_2d_image_data_url(smiles):
    """从 SMILES 字符串生成 PNG 图像的 Base64 Data URL"""
    try:
        mol = Chem.MolFromSmiles(smiles)
        if mol is None: return None
        # 尝试生成 2D 坐标
        AllChem.Compute2DCoords(mol)
        drawer = rdMolDraw2D.MolDraw2DCairo(200, 200)
        drawer.drawOptions().addStereoAnnotation = True
        drawer.DrawMolecule(mol)
        drawer.FinishDrawing()
        
        png_bytes = drawer.GetPNGData() 
        base64_data = base64.b64encode(png_bytes).decode('utf-8')
        return f"data:image/png;base64,{base64_data}"
    except Exception as e:
        print(f"Error generating 2D image for {smiles}: {e}", file=sys.stderr)
        return None

