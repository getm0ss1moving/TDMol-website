# --- 新增函数: 更新前端的历史记录文件 ---
def update_frontend_history(task_info, frontend_user, frontend_host, frontend_result_path):
    """
    通过 SCP 获取前端 task_history.json，追加新记录，然后传回。
    注意：此函数需在后端服务器上执行。
    """
    remote_history_path = os.path.join(frontend_result_path, HISTORY_FILENAME)
    local_temp_path = os.path.join('/tmp', HISTORY_FILENAME)
    
    print(f"[History] Attempting to update {remote_history_path}...")

    transport = None
    sftp = None
    try:
        # 1. 建立 SSH 连接
        transport = paramiko.Transport((frontend_host, FRONTEND_PORT))
        transport.connect(username=frontend_user, password=FRONTEND_PASS)
        sftp = paramiko.SFTPClient.from_transport(transport)

        # 2. 从前端下载现有的历史记录文件
        try:
            sftp.get(remote_history_path, local_temp_path)
            with open(local_temp_path, 'r', encoding='utf-8') as f:
                history = json.load(f)
            if not isinstance(history, list):
                history = [] # 格式错误则重置
            print("[History] Downloaded existing history.")
        except FileNotFoundError:
            history = [] # 文件不存在，创建新的列表
            print("[History] Remote history file not found. Creating new list.")
        except Exception as e:
            print(f"[History] Error reading existing JSON: {e}. Starting with empty list.", file=sys.stderr)
            history = []
            
        # 3. 检查并更新历史记录 (避免重复添加)
        existing_task_ids = {t['task_id'] for t in history}
        if task_info['task_id'] not in existing_task_ids:
            history.insert(0, task_info) # 插入到最前面
            print(f"[History] Added new task {task_info['task_id']}.")
        
        # 4. 将更新后的内容写入本地临时文件
        with open(local_temp_path, 'w', encoding='utf-8') as f:
            json.dump(history, f, ensure_ascii=False, indent=4)
        
        # 5. 上传更新后的文件回前端服务器
        sftp.put(local_temp_path, remote_history_path)
        print(f"[History] Successfully uploaded updated {HISTORY_FILENAME} back to frontend.")

    except Exception as e:
        print(f"[History] Critical error during history update: {e}", file=sys.stderr)
        # 忽略此错误，因为主任务结果已回传
        
    finally:
        if sftp: sftp.close()
        if transport: transport.close()
        # 清理本地临时文件
        if os.path.exists(local_temp_path):
            os.remove(local_temp_path)


