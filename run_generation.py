#!/usr/bin/env python3
"""
run_generation.py - 包装app.py的功能，使其可以被shell脚本调用
类似于RNAJog中的run.py
"""

import sys
import os
import argparse
import json
import numpy as np
import torch
from rdkit import Chem
from rdkit.Chem import AllChem

# 导入model_runner
try:
    from model_runner import initialize_models, generate_and_evaluate_for_webapp
    from qm9.rdkit_functions import build_molecule
    from configs.datasets_config import get_dataset_info
except ImportError as e:
    print(f"Error: Required modules not found: {e}")
    sys.exit(1)

# 全局缓存：避免每次都重建字典
_atomic_number_to_idx_cache = None

def _get_atomic_number_to_idx(dataset_info):
    """获取原子序数到索引的映射（缓存版本）"""
    global _atomic_number_to_idx_cache
    if _atomic_number_to_idx_cache is None:
        atom_decoder = dataset_info['atom_decoder']
        periodic_table = Chem.GetPeriodicTable()
        _atomic_number_to_idx_cache = {
            periodic_table.GetAtomicNumber(atom_name): idx
            for idx, atom_name in enumerate(atom_decoder)
        }
    return _atomic_number_to_idx_cache

def save_molecule_files(mol_data, task_id, mol_index, output_dir, dataset_info):
    """保存分子的XYZ和SDF文件（优化版本）"""

    # 快速失败：检查SMILES是否有效
    if not mol_data['smiles'] or mol_data['smiles'] == 'Invalid Molecule':
        print(f"  Molecule {mol_index} has invalid SMILES, skipping")
        return None

    try:
        # 获取缓存的映射字典
        atomic_number_to_idx = _get_atomic_number_to_idx(dataset_info)

        # 构建分子对象（只构建一次！）
        positions_tensor = torch.tensor(mol_data['coords'], dtype=torch.float32)
        atom_types_tensor = torch.tensor(
            [atomic_number_to_idx[atom_num] for atom_num in mol_data['atoms']],
            dtype=torch.long
        )

        mol = build_molecule(positions_tensor, atom_types_tensor, dataset_info)

        if not mol:
            print(f"  Molecule {mol_index} failed to build, skipping")
            return None

        # 检测片段（轻量级操作）
        frag_atoms_list = Chem.rdmolops.GetMolFrags(mol, asMols=False)

        # 根据片段数量决定是否需要清洗
        if len(frag_atoms_list) > 1:
            # 多片段：需要清洗
            largest_frag_indices = max(frag_atoms_list, key=len)
            num_removed = len(mol_data['atoms']) - len(largest_frag_indices)

            print(f"  Molecule {mol_index}: {len(frag_atoms_list)} fragments, removing {num_removed} atoms")

            # 提取清洗后的数据
            cleaned_atoms = mol_data['atoms'][list(largest_frag_indices)]
            cleaned_coords = mol_data['coords'][list(largest_frag_indices)]

            # 获取清洗后的分子对象（从RDKit片段中提取，无需重新构建）
            mol_frags = Chem.rdmolops.GetMolFrags(mol, asMols=True, sanitizeFrags=False)
            mol = max(mol_frags, key=lambda m: m.GetNumAtoms())
        else:
            # 单片段：直接使用原始数据，无需清洗
            cleaned_atoms = mol_data['atoms']
            cleaned_coords = mol_data['coords']

        # 保存XYZ文件（优化：直接写入，不生成中间字符串）
        xyz_file = os.path.join(output_dir, f'molecule_{mol_index}.xyz')
        xyz_map = {1: 'H', 6: 'C', 7: 'N', 8: 'O', 9: 'F'}

        with open(xyz_file, 'w') as f:
            f.write(f"{len(cleaned_atoms)}\nGenerated by EDM\n")
            for atom_num, coord in zip(cleaned_atoms, cleaned_coords):
                symbol = xyz_map.get(atom_num, 'X')
                f.write(f"{symbol}\t{coord[0]:.4f}\t{coord[1]:.4f}\t{coord[2]:.4f}\n")

        # 保存SDF文件（优化：直接设置坐标，减少类型转换）
        sdf_file = os.path.join(output_dir, f'molecule_{mol_index}.sdf')
        conf = Chem.Conformer(mol.GetNumAtoms())

        for i, coord in enumerate(cleaned_coords):
            conf.SetAtomPosition(i, (float(coord[0]), float(coord[1]), float(coord[2])))

        mol.RemoveAllConformers()
        mol.AddConformer(conf)

        writer = Chem.SDWriter(sdf_file)
        writer.write(mol)
        writer.close()

        return xyz_file

    except Exception as e:
        print(f"Error: Molecule {mol_index} save failed: {e}")
        return None

def main():
    parser = argparse.ArgumentParser(description='EDM Molecule Generation')
    parser.add_argument('--task_id', required=True, help='Task ID')
    parser.add_argument('--input_file', required=True, help='Input text file with molecule description')
    parser.add_argument('--output_dir', required=True, help='Output directory')
    parser.add_argument('--num_molecules', type=int, default=100, help='Number of molecules to generate (default: 100)')
    parser.add_argument('--guidance_scale', type=float, default=5.0, help='Guidance scale for generation (default: 5.0)')

    args = parser.parse_args()

    # 从命令行参数获取生成数量和guidance scale
    num_molecules = args.num_molecules
    guidance_scale = args.guidance_scale

    # 读取用户输入
    with open(args.input_file, 'r', encoding='utf-8') as f:
        user_input = f.read().strip()

    print(f"Task ID: {args.task_id}")
    print(f"User input: {user_input}")
    print(f"Number of molecules to generate: {num_molecules}")
    print(f"Guidance scale: {guidance_scale}")

    # 创建输出目录
    os.makedirs(args.output_dir, exist_ok=True)

    # 初始化模型
    print("Initializing models...")
    model_objects = initialize_models()
    dataset_info = model_objects['dataset_info']

    # 生成分子
    print(f"\n{'='*60}")
    print(f"Starting molecule generation...")
    print(f"{'='*60}\n")

    # 调用model_runner中的生成函数，一次性生成所有分子
    generated_molecules, evaluation_summary = generate_and_evaluate_for_webapp(
        user_input, model_objects, args.task_id,
        num_samples=num_molecules,
        guidance_scale=guidance_scale
    )

    # 处理生成的分子
    results_list = []

    if evaluation_summary.get('error_message'):
        print(f"ERROR: {evaluation_summary['error_message']}")
        return

    print(f"\nSaving generated molecules...")
    saved_count = 0
    for i, molecule in enumerate(generated_molecules, start=1):
        # 保存分子文件 (传递dataset_info，会自动清洗多余片段)
        xyz_file = save_molecule_files(molecule, args.task_id, i, args.output_dir, dataset_info)

        # 只在保存成功时添加到结果列表
        if xyz_file is not None:
            results_list.append({
                'mol_id': f"{args.task_id}_{i}",
                'smiles': molecule['smiles'],
                'score': 1.0,  # 有效分子的得分为1.0
                'atoms': molecule['atoms'].tolist(),
                'coords': molecule['coords'].tolist(),
                'xyz_file': xyz_file
            })
            saved_count += 1
            print(f"  ✓ Molecule {i} saved successfully: {molecule['smiles'][:60]}...")
        else:
            print(f"  ✗ Molecule {i} failed to save")

    # 保存结果摘要到JSON文件
    summary_file = os.path.join(args.output_dir, 'summary.json')
    summary_data = {
        'task_id': args.task_id,
        'user_input': user_input,
        'num_molecules': num_molecules,
        'guidance_scale': guidance_scale,
        'total_generated': len(generated_molecules),
        'total_attempted': evaluation_summary['total_samples'],
        'valid_count': evaluation_summary['valid_molecules'],
        'invalid_count': evaluation_summary['invalid_molecules'],
        'saved_count': saved_count,  # 实际成功保存的分子数
        'processing_time': evaluation_summary['processing_time'],
        'results': results_list
    }

    with open(summary_file, 'w', encoding='utf-8') as f:
        json.dump(summary_data, f, ensure_ascii=False, indent=4)

    print(f"\n{'='*60}")
    print(f"Generation complete!")
    print(f"  Total attempted: {evaluation_summary['total_samples']}")
    print(f"  Valid molecules: {evaluation_summary['valid_molecules']}")
    print(f"  Invalid molecules: {evaluation_summary['invalid_molecules']}")
    print(f"  Successfully saved: {saved_count}/{len(generated_molecules)}")
    print(f"  Processing time: {evaluation_summary['processing_time']} seconds")
    print(f"  Results saved to: {args.output_dir}")
    print(f"  Summary saved to: {summary_file}")
    print(f"{'='*60}")

if __name__ == "__main__":
    main()
